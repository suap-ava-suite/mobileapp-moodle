const postcss = require('postcss');
const selectors = require('postcss-selector-parser');

/** Reuses the existing iframe theme inside Angular's component style boundary. */
function painelAngularTheme(css) {
    const sheet = postcss.parse(css);
    sheet.walkRules(rule => {
        // Keyframe selectors are animation steps, not DOM selectors.
        for (let parent = rule.parent; parent; parent = parent.parent) {
            if (parent.type === 'atrule' && /keyframes$/i.test(parent.name)) return;
        }
        rule.selector = selectors(ast => {
            ast.each(selector => {
                const compounds = [[]];
                selector.each(node => {
                    if (node.type === 'combinator') compounds.push([]);
                    else compounds[compounds.length - 1].push(node);
                });
                let previousHost;
                for (const nodes of compounds) {
                    const root = nodes.find(node => (node.type === 'tag' && ['html', 'body', 'ion-app'].includes(node.value)) ||
                        (node.type === 'pseudo' && node.value === ':root'));
                    if (!root) { previousHost = undefined; continue; }
                    const modifiers = nodes.filter(node => node !== root);
                    const inheritedDark = modifiers.some(node => node.type === 'class' && node.value === 'dark');
                    // body.foo ion-app is the same local host, not a descendant host.
                    if (previousHost && !modifiers.length && root.prev()?.type === 'combinator' && root.prev().value.trim() === '') {
                        root.prev().remove();
                        root.remove();
                        continue;
                    }
                    const host = selectors.pseudo({ value: inheritedDark ? ':host-context' : ':host' });
                    if (modifiers.length) host.append(selectors.selector({ nodes: modifiers.map(node => node.clone()) }));
                    for (const node of modifiers) node.remove();
                    root.replaceWith(host);
                    previousHost = host;
                }
            });
        }).processSync(rule.selector);
    });
    sheet.walkDecls(decl => {
        // Cordova/Ionic owns system bar and cutout measurements. In the standalone
        // panel env() can be zero on Android; it must not reset the native host.
        if (decl.parent.type === 'rule' && decl.parent.selector === ':host' &&
            /^--ion-safe-area-(top|right|bottom|left)$/.test(decl.prop)) {
            decl.value = 'inherit';
        }
        decl.value = decl.value.replace(/url\((["']?)static\//g, 'url($1../mobilemoodle/static/');
    });
    return '/* Generated by mobilemoodle/build.mjs from painel.scss. Do not edit directly. */\n' + sheet.toString();
}
module.exports = { painelAngularTheme };
